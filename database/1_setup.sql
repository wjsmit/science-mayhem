CREATE OR REPLACE FUNCTION public.sci_class_open(p_class text, p_code text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_pid text := sci.code_id(p_code); v_class sci.classes; v_up text := upper(regexp_replace(coalesce(p_class,''), '[^A-Za-z]', '', 'g'));
begin
  if v_pid is null or not exists (select 1 from sci.profiles where id = v_pid) then raise exception 'not_found'; end if;
  select * into v_class from sci.classes where code = v_up;
  if v_class.id is null then perform pg_sleep(1); raise exception 'no_class'; end if;
  return jsonb_build_object('label', v_class.label,
    'names', coalesce((select jsonb_agg(jsonb_build_object('rid', r.id, 'name', r.real_name) order by r.real_name)
                         from sci.roster r where r.class_id = v_class.id and r.profile_id is null), '[]'::jsonb));
end $function$;

CREATE OR REPLACE FUNCTION public.sci_class_claim(p_class text, p_code text, p_rid bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_pid text := sci.code_id(p_code); v_class sci.classes; v_up text := upper(regexp_replace(coalesce(p_class,''), '[^A-Za-z]', '', 'g')); n int; v_track text; v_stage text;
begin
  if v_pid is null or not exists (select 1 from sci.profiles where id = v_pid) then raise exception 'not_found'; end if;
  select * into v_class from sci.classes where code = v_up;
  if v_class.id is null then raise exception 'no_class'; end if;
  if exists (select 1 from sci.roster where profile_id = v_pid) then raise exception 'already_linked'; end if;
  update sci.roster set profile_id = v_pid where id = p_rid and class_id = v_class.id and profile_id is null returning track, stage into v_track, v_stage;
  get diagnostics n = row_count;
  if n = 0 then raise exception 'name_taken'; end if;
  return jsonb_build_object('class', v_class.label, 'track', v_track, 'stage', v_stage);
end $function$;

CREATE OR REPLACE FUNCTION public.sci_class_mine(p_code text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_pid text := sci.code_id(p_code); v_label text; v_track text; v_stage text;
begin
  if v_pid is null then return null; end if;
  select c.label, r.track, r.stage into v_label, v_track, v_stage from sci.roster r join sci.classes c on c.id = r.class_id where r.profile_id = v_pid;
  if v_label is null then return null; end if;
  return jsonb_build_object('class', v_label, 'track', v_track, 'stage', v_stage);
end $function$;

