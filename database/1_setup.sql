CREATE OR REPLACE FUNCTION public.sci_name_available(p_name text)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_key text := sci.name_key(p_name); v_up text := upper(regexp_replace(coalesce(p_name,''), '[^A-Za-z0-9]', '', 'g'));
begin
  if char_length(v_key) < 3 then return false; end if;
  if v_up ~ '^([A-Z]{3,8}[0-9]{4}|[A-Z]{9,30})$'
     and exists (select 1 from sci.profiles where id = encode(extensions.digest('sci|' || v_up, 'sha256'), 'hex')) then return false; end if;
  return not exists (select 1 from sci.profiles where id = encode(extensions.digest('sci|n|' || v_key, 'sha256'), 'hex'));
end $function$;

