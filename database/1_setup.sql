CREATE OR REPLACE FUNCTION public.sci_profile_rename(p_code text, p_name text, p_color integer DEFAULT 0)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_old text := sci.code_id(p_code); v_key text := sci.name_key(p_name); v_name text := sci.clean_name(p_name);
        v_new text; v_data jsonb; v_up text := upper(regexp_replace(sci.clean_name(p_name), '[^A-Za-z0-9]', '', 'g'));
        v_now bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
begin
  if v_old is null then raise exception 'invalid_code'; end if;
  if char_length(v_key) < 3 then raise exception 'bad_name'; end if;
  perform 1 from sci.profiles where id = v_old for update;
  if not found then raise exception 'not_found'; end if;
  v_new := encode(extensions.digest('sci|n|' || v_key, 'sha256'), 'hex');
  if v_new <> v_old then
    if exists (select 1 from sci.profiles where id = v_new) then raise exception 'taken'; end if;
    if v_up ~ '^([A-Z]{3,8}[0-9]{4}|[A-Z]{9,30})$'
       and exists (select 1 from sci.profiles where id = encode(extensions.digest('sci|' || v_up, 'sha256'), 'hex')) then
      raise exception 'taken';
    end if;
    update sci.profiles set id = v_new where id = v_old;
  end if;
  update sci.profiles set data = data || jsonb_build_object('name', v_name, 'color', least(greatest(coalesce(p_color,0),0),7), 'updated', v_now), updated_at = now()
   where id = v_new returning data into v_data;
  return jsonb_build_object('code', v_name, 'data', v_data);
end $function$;

CREATE OR REPLACE FUNCTION public.sci_profile_apply_round(p_code text, p_delta jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_id text := sci.code_id(p_code);
  v_data jsonb; v_r int; v_w int; v_bs int; v_sc int; v_du int; v_mx int; v_m text; v_key text; v_best int; v_tk text; v_sg text;
  v_k text; v_fv jsonb; v_cur jsonb; v_nr int; v_nm int; v_entry jsonb; v_recent jsonb;
  v_now bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
begin
  if v_id is null then raise exception 'invalid_code'; end if;
  if p_delta is null or jsonb_typeof(p_delta) <> 'object' or pg_column_size(p_delta) > 20000 then raise exception 'bad_round'; end if;
  select data into v_data from sci.profiles where id = v_id for update;
  if v_data is null then raise exception 'not_found'; end if;
  v_r  := least(greatest(coalesce((p_delta->>'r')::int, 0), 0), 500);
  v_w  := least(greatest(coalesce((p_delta->>'w')::int, 0), 0), 500);
  v_bs := least(greatest(coalesce((p_delta->>'bs')::int, 0), 0), 500);
  v_sc := least(greatest(coalesce((p_delta->>'sc')::int, 0), 0), 20000);
  v_du := coalesce((p_delta->>'du')::int, 60);
  if v_du not in (45, 60, 90) then v_du := 60; end if;
  v_mx := least(greatest(coalesce((p_delta->>'mx')::int, 12), 6), 12);
  v_m  := case when p_delta->>'m' = 'solo' then 'solo' else 'room' end;
  v_tk := case when p_delta->>'tk' = any (array['ptable','states','cells','mixed']) then p_delta->>'tk' else 'ptable' end;
  v_sg := case when p_delta->>'sg' = 'ig' then 'ig' else 'ks3' end;
  if v_r + v_w = 0 then return v_data; end if;

  v_data := v_data || jsonb_build_object('best', coalesce(v_data->'best', '{}'::jsonb),
                                         'facts', coalesce(v_data->'facts', '{}'::jsonb),
                                         'recent', coalesce(v_data->'recent', '[]'::jsonb));
  v_data := jsonb_set(v_data, '{rounds}', to_jsonb(coalesce((v_data->>'rounds')::int, 0) + 1));
  v_data := jsonb_set(v_data, '{right}', to_jsonb(coalesce((v_data->>'right')::bigint, 0) + v_r));
  v_data := jsonb_set(v_data, '{wrong}', to_jsonb(coalesce((v_data->>'wrong')::bigint, 0) + v_w));
  v_data := jsonb_set(v_data, '{bestStreak}', to_jsonb(greatest(coalesce((v_data->>'bestStreak')::int, 0), v_bs)));
  v_data := jsonb_set(v_data, '{bestScore}', to_jsonb(greatest(coalesce((v_data->>'bestScore')::int, 0), v_sc)));
  v_key := v_du::text || '-' || v_tk || '-' || v_sg;
  v_best := greatest(coalesce((v_data->'best'->>v_key)::int, 0), v_sc);
  v_data := jsonb_set(v_data, array['best', v_key], to_jsonb(v_best), true);

  for v_k, v_fv in
    select key, value from jsonb_each(case when jsonb_typeof(p_delta->'fr') = 'object' then p_delta->'fr' else '{}'::jsonb end) limit 200
  loop
    continue when v_k !~ '^[a-z]{2,6}[0-9]{1,4}$' or jsonb_typeof(v_fv) <> 'array';
    v_nr := least(greatest(coalesce((v_fv->>0)::int, 0), 0), 500);
    v_nm := least(greatest(coalesce((v_fv->>1)::int, 0), 0), 500);
    v_cur := coalesce(v_data->'facts'->v_k, '[0,0]'::jsonb);
    v_data := jsonb_set(v_data, array['facts', v_k],
      jsonb_build_array(coalesce((v_cur->>0)::int, 0) + v_nr, coalesce((v_cur->>1)::int, 0) + v_nm), true);
  end loop;

  v_entry := jsonb_build_object('t', v_now, 'sc', v_sc, 'r', v_r, 'w', v_w, 'du', v_du, 'mx', v_mx, 'm', v_m, 'tk', v_tk, 'sg', v_sg);
  select coalesce(jsonb_agg(s.e order by s.ord), '[]'::jsonb) into v_recent from (
    select 0::bigint as ord, v_entry as e
    union all
    select t.o, t.x from jsonb_array_elements(coalesce(v_data->'recent', '[]'::jsonb)) with ordinality as t(x, o)
  ) s where s.ord < 10;
  v_data := jsonb_set(v_data, '{recent}', v_recent);

  if jsonb_exists(p_delta, 'name') then
    v_data := jsonb_set(v_data, '{name}', to_jsonb(sci.clean_name(p_delta->>'name')));
  end if;
  if jsonb_exists(p_delta, 'color') then
    v_data := jsonb_set(v_data, '{color}', to_jsonb(least(greatest(coalesce((p_delta->>'color')::int, 0), 0), 7)));
  end if;
  v_data := jsonb_set(v_data, '{updated}', to_jsonb(v_now));

  update sci.profiles set data = v_data, updated_at = now() where id = v_id;
  return v_data;
end $function$;

CREATE OR REPLACE FUNCTION public.sci_leaderboard(p_code text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.code_id(p_code); v_top jsonb; v_me jsonb; v_total int;
begin
  select count(*) into v_total from sci.profiles where coalesce((data->>'rounds')::int,0) > 0;
  select coalesce(jsonb_agg(x order by (x->>'rank')::int), '[]'::jsonb) into v_top from (
    select jsonb_build_object('rank', row_number() over (order by (p.data->>'bestScore')::int desc, (p.data->>'rounds')::int desc),
      'name', coalesce(r.real_name, p.data->>'name'), 'color', (p.data->>'color')::int, 'av', p.data->>'av', 'best', (p.data->>'bestScore')::int, 'streak', (p.data->>'bestStreak')::int,
      'rounds', (p.data->>'rounds')::int,
      'acc', case when (p.data->>'right')::int + (p.data->>'wrong')::int > 0 then round(100.0*(p.data->>'right')::int/((p.data->>'right')::int+(p.data->>'wrong')::int)) else 0 end) as x
    from sci.profiles p left join sci.roster r on r.profile_id = p.id where coalesce((p.data->>'rounds')::int,0) > 0
    order by (p.data->>'bestScore')::int desc, (p.data->>'rounds')::int desc limit 10) t;
  if v_id is not null then
    select jsonb_build_object('rank', rk) into v_me from (
      select id, row_number() over (order by (data->>'bestScore')::int desc, (data->>'rounds')::int desc) as rk
      from sci.profiles where coalesce((data->>'rounds')::int,0) > 0) q where id = v_id;
  end if;
  return jsonb_build_object('total', v_total, 'top', v_top, 'me', v_me);
end $function$;

