CREATE OR REPLACE FUNCTION public.sci_profile_create(p_name text, p_color integer DEFAULT 0)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_now bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
  v_name text := sci.clean_name(p_name); v_key text := sci.name_key(p_name); v_up text; v_data jsonb; v_id text;
begin
  if char_length(v_key) < 3 then raise exception 'bad_name'; end if;
  if (select count(*) from sci.profiles) >= 100000 then raise exception 'full'; end if;
  v_up := upper(regexp_replace(v_name, '[^A-Za-z0-9]', '', 'g'));
  if v_up ~ '^([A-Z]{3,8}[0-9]{4}|[A-Z]{9,30})$'
     and exists (select 1 from sci.profiles where id = encode(extensions.digest('sci|' || v_up, 'sha256'), 'hex')) then
    raise exception 'taken';
  end if;
  v_id := encode(extensions.digest('sci|n|' || v_key, 'sha256'), 'hex');
  v_data := jsonb_build_object('name', v_name, 'color', least(greatest(coalesce(p_color, 0), 0), 7),
    'rounds', 0, 'right', 0, 'wrong', 0, 'bestStreak', 0, 'bestScore', 0,
    'best', '{}'::jsonb, 'facts', '{}'::jsonb, 'recent', '[]'::jsonb, 'created', v_now, 'updated', v_now);
  insert into sci.profiles (id, data) values (v_id, v_data) on conflict (id) do nothing;
  if not found then raise exception 'taken'; end if;
  return v_name;
end $function$;

