CREATE OR REPLACE FUNCTION public.sci_admin_delete(p_code text, p_pin text, p_handle text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.admin_ok(p_code, p_pin); n int;
begin
  if v_id is null then raise exception 'not_allowed'; end if;
  if p_handle is null or char_length(p_handle) <> 12 then raise exception 'bad_handle'; end if;
  delete from sci.profiles where left(id,12) = p_handle and id <> v_id;
  get diagnostics n = row_count;
  return n;
end $function$;

CREATE OR REPLACE FUNCTION public.sci_admin_set_pin(p_code text, p_pin text, p_new text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.admin_ok(p_code, p_pin); v_salt text := encode(extensions.gen_random_bytes(8),'hex');
begin
  if v_id is null then raise exception 'not_allowed'; end if;
  if char_length(coalesce(p_new,'')) < 6 then raise exception 'weak_pin'; end if;
  update sci.admins set salt = v_salt, pin_hash = encode(extensions.digest(v_salt || p_new, 'sha256'), 'hex') where profile_id = v_id;
  return true;
end $function$;

CREATE OR REPLACE FUNCTION public.sci_admin_import(p_code text, p_pin text, p_label text, p_names text[], p_track text, p_stage text DEFAULT 'ks3')
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.admin_ok(p_code, p_pin); v_label text := left(btrim(coalesce(p_label,'')), 20); v_cid bigint; v_cc text; v_n text; v_add int := 0; v_stage text := case when p_stage = 'ig' then 'ig' else 'ks3' end; n int; i int;
        v_track text := case when p_track = any (array['ptable','states','cells','mixed']) then p_track else 'ptable' end;
begin
  if v_id is null then raise exception 'not_allowed'; end if;
  if v_label = '' then raise exception 'bad_label'; end if;
  if coalesce(array_length(p_names,1),0) > 80 then raise exception 'too_many'; end if;
  select id, code into v_cid, v_cc from sci.classes where lower(label) = lower(v_label);
  if v_cid is null then
    for i in 1..20 loop
      v_cc := (select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ', 1 + floor(random()*24)::int, 1), '') from generate_series(1,5));
      begin
        insert into sci.classes (label, code) values (v_label, v_cc) returning id into v_cid;
        exit;
      exception when unique_violation then v_cid := null;
      end;
    end loop;
    if v_cid is null then raise exception 'try_again'; end if;
  end if;
  foreach v_n in array coalesce(p_names, array[]::text[]) loop
    v_n := left(btrim(regexp_replace(coalesce(v_n,''), '[[:cntrl:]]', '', 'g')), 40);
    if char_length(v_n) < 2 then continue; end if;
    insert into sci.roster (class_id, real_name, track, stage) values (v_cid, v_n, v_track, v_stage) on conflict do nothing;
    get diagnostics n = row_count;
    v_add := v_add + n;
  end loop;
  return jsonb_build_object('class', v_label, 'code', v_cc, 'added', v_add);
end $function$;

CREATE OR REPLACE FUNCTION public.sci_admin_roster(p_code text, p_pin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.admin_ok(p_code, p_pin);
begin
  if v_id is null then raise exception 'not_allowed'; end if;
  return jsonb_build_object(
    'classes', coalesce((select jsonb_agg(jsonb_build_object('label', label, 'code', code) order by label) from sci.classes), '[]'::jsonb),
    'rows', coalesce((select jsonb_agg(jsonb_build_object(
        'rid', r.id, 'class', c.label, 'real', r.real_name, 'track', r.track, 'stage', r.stage, 'user', p.data->>'name',
        'rounds', (p.data->>'rounds')::int, 'right', (p.data->>'right')::int, 'wrong', (p.data->>'wrong')::int,
        'best', (p.data->>'bestScore')::int, 'last', (p.data->>'updated')::bigint, 'facts', p.data->'facts')
        order by c.label, r.real_name)
      from sci.roster r join sci.classes c on c.id = r.class_id left join sci.profiles p on p.id = r.profile_id), '[]'::jsonb));
end $function$;

CREATE OR REPLACE FUNCTION public.sci_admin_set_level(p_code text, p_pin text, p_rid bigint, p_track text, p_stage text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.admin_ok(p_code, p_pin); n int;
begin
  if v_id is null then raise exception 'not_allowed'; end if;
  if not (p_track = any (array['ptable','states','cells','mixed'])) then raise exception 'bad_track'; end if;
  if not (p_stage = any (array['ks3','ig'])) then raise exception 'bad_stage'; end if;
  update sci.roster set track = p_track, stage = p_stage where id = p_rid;
  get diagnostics n = row_count;
  return n;
end $function$;

