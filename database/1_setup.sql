-- Science Mayhem: one-time database setup.
-- Paste ALL of this into Supabase > SQL Editor (in the science-mayhem project) and press Run.
-- It is safe to run twice. A second small script (2_teacher.sql) then makes you the teacher.
--
-- This is a standalone copy of the times table game's database, adapted for science:
--   * levels are science topics: ptable, states, cells, mixed
--   * every student also has a stage: 'ks3' (lower secondary) or 'ig' (IGCSE)
--   * fact keys look like pt12 (topic letters + question number)
--   * personal bests are kept per round length, topic and stage
--   * sci_admin_set_level sets a student's topic and stage in one call
-- The tables can't be read directly from the browser; it can only call the game's own sci_* functions.

create extension if not exists pgcrypto with schema extensions;

create schema if not exists sci;
revoke all on schema sci from public, anon, authenticated;

create table if not exists sci.profiles (
  id text primary key,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table sci.profiles enable row level security;   -- no policies: nobody can touch the table directly

create table if not exists sci.admins (
  profile_id text primary key references sci.profiles(id) on update cascade,
  salt text not null,
  pin_hash text not null
);
alter table sci.admins enable row level security;

create table if not exists sci.classes (
  id bigint generated by default as identity primary key,
  label text not null,
  code text not null unique,
  created_at timestamptz not null default now()
);
create unique index if not exists classes_label_key on sci.classes (lower(label));
alter table sci.classes enable row level security;

create table if not exists sci.roster (
  id bigint generated by default as identity primary key,
  class_id bigint not null references sci.classes(id),
  real_name text not null,
  profile_id text references sci.profiles(id) on update cascade on delete set null,
  created_at timestamptz not null default now(),
  track text not null default 'ptable',
  stage text not null default 'ks3'
);
create unique index if not exists roster_name_key on sci.roster (class_id, lower(real_name));
create unique index if not exists roster_profile_key on sci.roster (profile_id) where profile_id is not null;
alter table sci.roster enable row level security;

-- ---------- helper functions (private: not reachable from the browser) ----------
CREATE OR REPLACE FUNCTION sci.clean_name(p text)
 RETURNS text
 LANGUAGE sql
 SET search_path TO ''
AS $function$
  select left(btrim(regexp_replace(coalesce(p, ''), '[[:cntrl:]]', '', 'g')), 20)
$function$;

CREATE OR REPLACE FUNCTION sci.name_key(p text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO ''
AS $function$
  select lower(regexp_replace(coalesce(p,''), '[^[:alnum:]]', '', 'g'))
$function$;

CREATE OR REPLACE FUNCTION sci.code_id(p_code text)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare v_up text := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
        v_key text := sci.name_key(p_code); v_legacy text;
begin
  if v_up ~ '^([A-Z]{3,8}[0-9]{4}|[A-Z]{9,30})$' then
    v_legacy := encode(extensions.digest('sci|' || v_up, 'sha256'), 'hex');
    if exists (select 1 from sci.profiles where id = v_legacy) then return v_legacy; end if;
  end if;
  if char_length(v_key) < 3 then return null; end if;
  return encode(extensions.digest('sci|n|' || v_key, 'sha256'), 'hex');
end $function$;

CREATE OR REPLACE FUNCTION sci.admin_ok(p_code text, p_pin text)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare v_id text := sci.code_id(p_code); v_ok boolean;
begin
  if v_id is null or p_pin is null then return null; end if;
  select (encode(extensions.digest(a.salt || p_pin, 'sha256'), 'hex') = a.pin_hash) into v_ok from sci.admins a where a.profile_id = v_id;
  if coalesce(v_ok,false) then return v_id; end if;
  perform pg_sleep(1);
  return null;
end $function$;

