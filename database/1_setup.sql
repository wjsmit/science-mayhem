-- Science Mayhem: one-time database setup. Paste ALL of this into Supabase > SQL Editor (the same project as the maths game) and press Run.
-- It makes a separate "sci" copy of the times table game's database, so students, classes, scores and
-- leaderboards for science never mix with the maths game. Nothing in the maths game (schema "tts") is changed.
--
-- Differences from the maths copy:
--   * levels are science topics: ptable, states, cells, mixed
--   * every student also has a stage: 'ks3' (lower secondary) or 'ig' (IGCSE)
--   * fact keys look like pt12 (topic letters + question number) instead of 6x7
--   * personal bests are kept per round length, topic and stage
--   * sci_admin_set_level sets a student's topic and stage in one call

create schema if not exists sci;
revoke all on schema sci from public, anon, authenticated;

create table if not exists sci.profiles (
  id text primary key,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table sci.profiles enable row level security;

create table if not exists sci.admins (
  profile_id text primary key references sci.profiles(id) on update cascade,
  salt text not null,
  pin_hash text not null
);
alter table sci.admins enable row level security;

create table if not exists sci.classes (
  id bigint generated by default as identity primary key,
  label text not null,
  code text not null unique,
  created_at timestamptz not null default now()
);
create unique index if not exists classes_label_key on sci.classes (lower(label));
alter table sci.classes enable row level security;

create table if not exists sci.roster (
  id bigint generated by default as identity primary key,
  class_id bigint not null references sci.classes(id),
  real_name text not null,
  profile_id text,
  created_at timestamptz not null default now(),
  track text not null default 'ptable',
  stage text not null default 'ks3'
);
create unique index if not exists roster_name_key on sci.roster (class_id, lower(real_name));
create unique index if not exists roster_profile_key on sci.roster (profile_id) where profile_id is not null;
alter table sci.roster enable row level security;

create or replace function pg_temp.pt(d text, a text, b text) returns text language plpgsql as $x$
begin
  if position(a in d) = 0 then raise exception 'patch target missing: %', a; end if;
  return replace(d, a, b);
end $x$;

-- Copy every function of the maths game into the sci schema, renaming tts -> sci and adjusting the science parts.
do $do$
declare r record; d text; pn text;
begin
  for r in
    select p.oid, p.proname from pg_proc p
    where (p.pronamespace = 'tts'::regnamespace or (p.pronamespace = 'public'::regnamespace and p.proname like 'tts\_%'))
      and not (p.proname = 'tts_admin_import' and pg_get_function_identity_arguments(p.oid) not like '%p_track%')
  loop
    pn := r.proname;
    d := pg_get_functiondef(r.oid);
    d := replace(d, $q$array['tables','addsub','bodmas','frac','alg1','alg2','alg3', 'alg4', 'muldiv', 'fracs', 'mixed', 'ineq']$q$,
                    $q$array['ptable','states','cells','mixed']$q$);
    d := replace(d, $q$else 'tables' end$q$, $q$else 'ptable' end$q$);

    if pn = 'tts_admin_import' then
      d := pg_temp.pt(d, $q$p_track text)$q$, $q$p_track text, p_stage text DEFAULT 'ks3')$q$);
      d := pg_temp.pt(d, $q$v_add int := 0;$q$, $q$v_add int := 0; v_stage text := case when p_stage = 'ig' then 'ig' else 'ks3' end;$q$);
      d := pg_temp.pt(d, $q$insert into tts.roster (class_id, real_name, track) values (v_cid, v_n, v_track)$q$,
                         $q$insert into tts.roster (class_id, real_name, track, stage) values (v_cid, v_n, v_track, v_stage)$q$);
    elsif pn = 'tts_admin_roster' then
      d := pg_temp.pt(d, $q$'track', r.track,$q$, $q$'track', r.track, 'stage', r.stage,$q$);
    elsif pn = 'tts_class_mine' then
      d := pg_temp.pt(d, $q$v_label text; v_track text;$q$, $q$v_label text; v_track text; v_stage text;$q$);
      d := pg_temp.pt(d, $q$select c.label, r.track into v_label, v_track$q$, $q$select c.label, r.track, r.stage into v_label, v_track, v_stage$q$);
      d := pg_temp.pt(d, $q$jsonb_build_object('class', v_label, 'track', v_track)$q$, $q$jsonb_build_object('class', v_label, 'track', v_track, 'stage', v_stage)$q$);
    elsif pn = 'tts_class_claim' then
      d := pg_temp.pt(d, $q$n int; v_track text;$q$, $q$n int; v_track text; v_stage text;$q$);
      d := pg_temp.pt(d, $q$returning track into v_track;$q$, $q$returning track, stage into v_track, v_stage;$q$);
      d := pg_temp.pt(d, $q$jsonb_build_object('class', v_class.label, 'track', v_track)$q$, $q$jsonb_build_object('class', v_class.label, 'track', v_track, 'stage', v_stage)$q$);
    elsif pn = 'tts_profile_apply_round' then
      d := pg_temp.pt(d, $q$v_tk text;$q$, $q$v_tk text; v_sg text;$q$);
      d := pg_temp.pt(d, $q$if v_r + v_w = 0 then return v_data; end if;$q$,
                         $q$v_sg := case when p_delta->>'sg' = 'ig' then 'ig' else 'ks3' end;
  if v_r + v_w = 0 then return v_data; end if;$q$);
      d := pg_temp.pt(d, $q$v_key := case when v_tk = 'tables' then v_du::text || '-' || v_mx::text else v_du::text || '-' || v_tk end;$q$,
                         $q$v_key := v_du::text || '-' || v_tk || '-' || v_sg;$q$);
      d := pg_temp.pt(d, $q$'^[0-9]{1,2}x[0-9]{1,2}$'$q$, $q$'^[a-z]{2,6}[0-9]{1,4}$'$q$);
      d := pg_temp.pt(d, $q$'tk', v_tk)$q$, $q$'tk', v_tk, 'sg', v_sg)$q$);
    end if;

    d := replace(d, 'tts', 'sci');
    execute d;
  end loop;
end $do$;

create or replace function public.sci_admin_set_level(p_code text, p_pin text, p_rid bigint, p_track text, p_stage text) returns integer
language plpgsql security definer set search_path = '' as $f$
declare v_id text := sci.admin_ok(p_code, p_pin); n int;
begin
  if v_id is null then raise exception 'not_allowed'; end if;
  if not (p_track = any (array['ptable','states','cells','mixed'])) then raise exception 'bad_track'; end if;
  if not (p_stage = any (array['ks3','ig'])) then raise exception 'bad_stage'; end if;
  update sci.roster set track = p_track, stage = p_stage where id = p_rid;
  get diagnostics n = row_count;
  return n;
end $f$;

-- The teacher who runs the maths game is also the teacher here: same name and same PIN (only the stored PIN hash is copied, inside the database).
do $do$
declare v_name text; v_color int;
begin
  select p.data->>'name', coalesce((p.data->>'color')::int, 0) into v_name, v_color
    from tts.admins a join tts.profiles p on p.id = a.profile_id limit 1;
  if v_name is not null and not exists (select 1 from sci.admins) then
    perform public.sci_profile_create(v_name, v_color);
    insert into sci.admins (profile_id, salt, pin_hash)
      select sci.code_id(v_name), a.salt, a.pin_hash from tts.admins a limit 1;
  end if;
end $do$;
