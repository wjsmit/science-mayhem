CREATE OR REPLACE FUNCTION public.sci_admin_list(p_code text, p_pin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_id text := sci.admin_ok(p_code, p_pin);
begin
  if v_id is null then raise exception 'not_allowed'; end if;
